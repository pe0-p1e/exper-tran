"""All-block surrogate visual diagnostics, no language loss or final-target access.

ILA-inspired baseline disturbance profiles and FDA(N)-motivated candidate
screening. Not a reproduction of either paper's attack or selection rule.
"""
import argparse
import csv
import fcntl
import json
import os
from pathlib import Path
import subprocess
import sys
import time
import numpy as np
import pp4_worker as base
from pp4_protocol import OUT,PREVIOUS,EXP,atomic_json,sha,records,development_ids,fingerprint
from supplement_registry import registry

ROOT=OUT/'all_layer_selection'
MODELS=['InternVL3.5-2B-HF','Gemma 4 E2B-it','CLIP ViT-L/14','DINOv2-Large','SigLIP2-So400m-patch14-384']


def lock():
    from commercial_matrix_pack import freeze
    from v6_v7_bridge_protocol import plan
    source=next(r['condition'] for r in plan()['ladder'] if r['label']=='old_deep_noDI')
    adv=OUT/'attacks/dev'/source['name']
    states=sorted(adv.glob('T*/batch_*/state.json'))
    if len(states)!=5:raise RuntimeError('Expected completed ten-image baseline')
    sources={str(p):sha(p) for p in states}
    value=dict(protocol='all_visual_layers_source_only_screen_v1',models=MODELS,model_revisions=registry(),
        development_ids=development_ids(),reference_count=48,all_block_outputs=True,
        source_sha256=sha(__file__),base_sources={n:sha(EXP/'src'/n) for n in ['vision_features.py','pp4_worker.py','representation_objectives.py','attack_optimizers.py']},
        baseline_attack_root=str(adv),baseline_state_hashes=sources,
        BF16=True,quantization=False,max_gpu_workers=2,per_worker_cap_gib=24,
        no_final_target_inference=True,no_commercial_calls=True,
        purpose='Per-layer class geometry and fixed-baseline semantic movement; no claim of measured new attack ASR',
        literature=['https://arxiv.org/abs/1907.10823','https://arxiv.org/abs/2004.14861','https://arxiv.org/abs/2107.14185'],
        adaptation='Layer disturbance profiling only, not ILA refinement/last-peak reproduction; no FDA auxiliary classifiers or FIA output-logit weighting',
        selection='Proxy-only preliminary signal-to-dispersion ranking; at most3 diverse candidates per model; must validate candidates with actual dev attacks before selecting a final method',
        caveat='Previously inspected dev10; baseline generated by E11. Its member models and held-out additional models are explicitly distinct; no universal semantics claim')
    freeze(ROOT/'protocol_lock.json',value)
    return value


def child(name):
    import torch
    import torch.nn.functional as F
    from vision_features import VisionProxy
    from v7_common import images
    frozen=json.loads((ROOT/'protocol_lock.json').read_text())
    if sha(__file__)!=frozen['source_sha256']:raise RuntimeError('Scan code changed')
    for n,h in frozen['base_sources'].items():
        if sha(EXP/'src'/n)!=h:raise RuntimeError('Feature code changed')
    for p,h in frozen['baseline_state_hashes'].items():
        if sha(p)!=h:raise RuntimeError('Baseline metadata changed')
    base.ROOT=ROOT;base.install_audit()
    depth=registry()[name]['expected_vision_depth'];fractions=[(i+.5)/depth for i in range(depth)]
    m=VisionProxy(name,fractions,role='all_layer_source_diagnostic');m.to('cuda')
    if m.layers!=list(range(depth)):raise RuntimeError('All-block mapping failed')
    dest=ROOT/'models'/name.replace('/','_');dest.mkdir(parents=True,exist_ok=True)
    began=time.time();banks={l:[] for l in m.layers}
    try:
        cache=dest/'reference_features.npz'
        identity=fingerprint([frozen['model_revisions'][name],frozen['base_sources'],
            [sha(OUT/'manifests/class_references'/f'class_references_{i:02d}.jsonl') for i in range(1,11)]])
        receipt=dest/'reference_features.json'
        if cache.exists() and receipt.exists() and json.loads(receipt.read_text())==dict(identity=identity,sha256=sha(cache)):
            with np.load(cache) as z:banks={l:z[f'z_{l}'] for l in m.layers}
        else:
            with torch.inference_mode():
                for label in range(1,11):
                    refs=records(OUT/'manifests/class_references'/f'class_references_{label:02d}.jsonl');g={l:[] for l in m.layers}
                    if len(refs)!=48:raise RuntimeError('Reference count differs')
                    for start in range(0,48,2):
                        f=m.features(images(refs[start:start+2]))
                        for l in m.layers:g[l].append(f[l][0].float().cpu().numpy())
                    for l in m.layers:banks[l].append(np.concatenate(g[l]))
                    print(name,'reference class',label,'/10, layers',depth,flush=True)
            banks={l:np.stack(v) for l,v in banks.items()}
            temp=cache.with_suffix('.tmp.npz');np.savez(temp,**{f'z_{l}':v for l,v in banks.items()});temp.replace(cache)
            atomic_json(receipt,dict(identity=identity,sha256=sha(cache)))
        centers={l:F.normalize(F.normalize(torch.from_numpy(banks[l]).cuda(),dim=-1).mean(1),dim=-1) for l in m.layers}
        rows=[]
        with torch.inference_mode():
            for path in sorted(Path(frozen['baseline_attack_root']).glob('T*/batch_*/state.json')):
                d=json.loads(path.read_text());s,t=d['source_label']-1,d['target_label']-1
                for rel,h in d['png_hashes'].items():
                    if sha(OUT/rel)!=h:raise RuntimeError('Baseline PNG changed')
                from primary_ml_cka.artifacts.png import load_png_tensor
                clean=torch.stack([load_png_tensor(OUT/p) for p in d['clean_paths']]).cuda()
                adv=torch.stack([load_png_tensor(OUT/p) for p in d['adv_paths']]).cuda()
                cf=m.features(clean);af=m.features(adv)
                for l in m.layers:
                    cz,az=cf[l][0].float(),af[l][0].float();c=centers[l]
                    source_refs=torch.from_numpy(banks[l][s]).cuda();target_refs=torch.from_numpy(banks[l][t]).cuda()
                    vs=float((1-F.cosine_similarity(source_refs,c[s][None])).mean())
                    vt=float((1-F.cosine_similarity(target_refs,c[t][None])).mean())
                    gap=float(1-(c[s]*c[t]).sum());sep=gap/max(vs+vt,1e-8)
                    for i,iid in enumerate(d['image_ids']):
                        cm=float(cz[i]@(c[t]-c[s]));am=float(az[i]@(c[t]-c[s]))
                        rows.append(dict(model=name,layer=l,normalized_depth=(l+1)/depth,transition=d['transition_id'],image_id=iid,
                            prototype_distance=gap,source_dispersion=vs,target_dispersion=vt,separation_dispersion_ratio=sep,
                            clean_margin_target_minus_source=cm,baseline_adv_margin=am,margin_change=am-cm,
                            target_pull=float((az[i]-cz[i])@c[t]),source_push=float((cz[i]-az[i])@c[s]),
                            baseline_relative_disturbance=float((az[i]-cz[i]).norm()/cz[i].norm().clamp_min(1e-12))))
        from pp4_campaign import table
        table(dest/'layers.csv',rows)
        atomic_json(dest/'complete.json',dict(status='MEASURED',model=name,layers=depth,observations=len(rows),
            reference_vectors=480*depth,seconds=time.time()-began,peak_reserved_gib=torch.cuda.max_memory_reserved()/2**30,
            feature_forward_calls=m.forward_calls,target_models_loaded=0,attack_ASR_measured=False))
    finally:m.close()


def campaign():
    frozen=lock()
    with (PREVIOUS/'scheduler.lock').open('a') as handle:
        fcntl.flock(handle,fcntl.LOCK_EX|fcntl.LOCK_NB)
        pending=[n for n in MODELS if not (ROOT/'models'/n.replace('/','_')/'complete.json').exists()]
        jobs=[];failures=[]
        while pending or jobs:
            for job in list(jobs):
                if job['process'].poll() is None:continue
                job['stream'].close();jobs.remove(job)
                if job['process'].returncode:failures.append(dict(model=job['model'],log=job['log']))
            if pending and len(jobs)<2:
                n=pending.pop(0);log=ROOT/'logs'/(n.replace('/','_')+'.log');log.parent.mkdir(parents=True,exist_ok=True)
                stream=log.open('a');env={**os.environ,'SUPPLEMENT_MEMORY_CAP_GIB':'24'}
                proc=subprocess.Popen([sys.executable,__file__,'--model',n],stdout=stream,stderr=subprocess.STDOUT,env=env,start_new_session=True)
                jobs.append(dict(model=n,process=proc,stream=stream,log=str(log)))
            atomic_json(ROOT/'progress.json',dict(pending=pending,active=[dict(model=j['model'],pid=j['process'].pid) for j in jobs],failures=failures))
            time.sleep(3)
        summary=[]
        for n in MODELS:
            path=ROOT/'models'/n.replace('/','_')/'layers.csv'
            if not path.exists():continue
            obs=list(csv.DictReader(path.open()))
            depth=registry()[n]['expected_vision_depth'];scores=[]
            for l in range(depth):
                r=[x for x in obs if int(x['layer'])==l]
                scores.append(dict(model=n,layer=l,N_images=len(r),
                    mean_separation_dispersion=float(np.mean([float(x['separation_dispersion_ratio']) for x in r])),
                    baseline_consensus_fraction=float(np.mean([float(x['margin_change'])>0 for x in r])),
                    mean_margin_change=float(np.mean([float(x['margin_change']) for x in r])),
                    interpretation='Source-side descriptive metric; not new attack ASR or proof of layer transferability'))
            summary+=scores
        from pp4_campaign import table
        table(ROOT/'reports/all_layers.csv',summary)
        atomic_json(ROOT/'completion.json',dict(status='COMPLETE' if not failures else 'PARTIAL_FAILURE',failures=failures,
            models_measured=len({r['model'] for r in summary}),layer_model_pairs=len(summary),native_target_inference=False))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--model',choices=MODELS);args=p.parse_args()
    if args.model:child(args.model)
    else:campaign()
